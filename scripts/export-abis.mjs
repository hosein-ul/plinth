// Exports ABIs (typed, `as const`) and deployable artifacts from the Foundry build.
// Usage: (cd contracts && forge build) && node scripts/export-abis.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256 } from "viem";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const targets = [
  ["src/MerchantVault.sol", "MerchantVault"],
  ["src/VaultFactory.sol", "VaultFactory"],
  ["src/InvoiceDeposit.sol", "InvoiceDeposit"],
  ["src/InvoiceFactory.sol", "InvoiceFactory"],
  ["src/PaymentRouter.sol", "PaymentRouter"],
  ["test/mocks/MockFiatToken.sol", "MockFiatToken"], // local development / tests only
];

const artifactsDir = join(root, "packages", "blockchain", "artifacts");
mkdirSync(artifactsDir, { recursive: true });

let abiTs = "// GENERATED by scripts/export-abis.mjs from contracts/out — do not edit.\n\n";
for (const [file, name] of targets) {
  const art = JSON.parse(readFileSync(join(out, `${file.split("/").pop()}`, `${name}.json`), "utf8"));
  abiTs += `export const ${name}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
  writeFileSync(
    join(artifactsDir, `${name}.json`),
    JSON.stringify(
      {
        contractName: name,
        sourceFile: file,
        bytecode: art.bytecode.object,
        deployedBytecode: art.deployedBytecode.object,
        immutableReferences: art.deployedBytecode.immutableReferences ?? {},
        // Hash of the runtime code with immutables zeroed: comparable across chains.
        deployedCodeHash: keccak256(maskImmutables(art.deployedBytecode.object, art.deployedBytecode.immutableReferences ?? {})),
      },
      null,
      2,
    ),
  );
}
mkdirSync(join(root, "packages", "blockchain", "src", "abi"), { recursive: true });
writeFileSync(join(root, "packages", "blockchain", "src", "abi", "generated.ts"), abiTs);
console.log("exported", targets.map((t) => t[1]).join(", "));

function maskImmutables(hex, refs) {
  const bytes = Buffer.from(hex.replace(/^0x/, ""), "hex");
  for (const list of Object.values(refs)) for (const { start, length } of list) bytes.fill(0, start, start + length);
  return `0x${bytes.toString("hex")}`;
}
