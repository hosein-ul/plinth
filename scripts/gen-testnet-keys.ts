/**
 * Generates THROWAWAY TESTNET keys into .env.testnet (gitignored) and prints the addresses to fund.
 * These keys must never hold real value. Mainnet keys are never generated or stored by this repo:
 * mainnet signing uses a keystore/HSM/KMS (see docs/operations.md).
 *
 *   pnpm keys:testnet
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const file = ".env.testnet";
const roles = ["DEPLOYER", "RELAYER", "MERCHANT_OWNER", "CUSTOMER"] as const;
const existing = existsSync(file) ? Object.fromEntries(readFileSync(file, "utf8").split("\n").filter((l) => l.includes("=") && !l.startsWith("#")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)])) : {};

const lines: string[] = ["# THROWAWAY TESTNET KEYS — generated by `pnpm keys:testnet`. Never fund these with real value. Gitignored."];
const addrs: Record<string, string> = {};
for (const r of roles) {
  const k = (existing[`${r}_PRIVATE_KEY`] as `0x${string}` | undefined) ?? generatePrivateKey();
  lines.push(`${r}_PRIVATE_KEY=${k}`);
  addrs[r] = privateKeyToAccount(k).address;
}
writeFileSync(file, lines.join("\n") + "\n", { mode: 0o600 });
console.log("Testnet key file:", file, existsSync(file) && Object.keys(existing).length ? "(kept existing keys)" : "(created)");
console.log("\nFund these on the testnets you want to run (faucets need a human):");
console.table(addrs);
console.log(`
Arc Testnet   (chain 5042002)  USDC is also the gas token → one faucet request covers gas AND payments.
              Faucet: https://faucet.circle.com  → network "Arc Testnet", paste the address.
Base Sepolia  (chain 84532)    needs Sepolia-Base ETH for gas AND test USDC (same Circle faucet for USDC).

Minimum useful funding:
  DEPLOYER   ≥ 1 USDC on Arc (contract deployment gas)         | ≥ 0.01 ETH on Base Sepolia
  RELAYER    ≥ 2 USDC on Arc (pays gas for sweeps/relays)      | ≥ 0.01 ETH on Base Sepolia
  CUSTOMER   ≥ 1 USDC on Arc (payments + its own transfer gas) | ≥ 1 USDC + 0.005 ETH on Base Sepolia
  MERCHANT_OWNER needs no funds to exist; it only signs if you test withdrawals.
`);
